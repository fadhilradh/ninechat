/**
 * Regenerates netlify/lib/auth-schema.sql from the installed Better Auth.
 *
 *   npm run auth:schema
 *
 * Better Auth adds columns between releases -- `account.issuer` showed up this
 * way -- and a hand-maintained copy silently drifts until sign-up fails with a
 * raw Postgres "column does not exist". Asking the library what tables it wants
 * removes the guesswork: the same option shape the deploy uses goes in, the
 * exact DDL comes out.
 *
 * The chat-history tables are appended verbatim from the block below; they are
 * ours, not Better Auth's.
 */
import { writeFileSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { getAuthTables } from "better-auth/db"

const tables = getAuthTables({
  emailAndPassword: { enabled: true },
  // Listing a provider makes sure the OAuth columns are present even on a
  // deploy that has not switched Google on yet.
  socialProviders: { google: { clientId: "x", clientSecret: "x" } },
})

/** Better Auth's field types, as Postgres understands them. */
function column(field) {
  switch (field.type) {
    case "boolean":
      return "BOOLEAN"
    case "number":
      return field.bigint ? "BIGINT" : "INTEGER"
    case "date":
      return "TIMESTAMPTZ"
    case "string[]":
    case "number[]":
      return "JSONB"
    default:
      return "TEXT"
  }
}

const lines = [
  "-- Better Auth core schema for Postgres.",
  "--",
  "-- GENERATED by scripts/generate-auth-schema.mjs from the installed",
  "-- better-auth. Do not hand-edit the tables above the chat-history block:",
  "-- run `npm run auth:schema` after upgrading better-auth instead.",
  "--",
  "-- Identifiers are quoted because Better Auth uses camelCase columns.",
  "",
]

for (const [, table] of Object.entries(tables)) {
  const name = table.modelName
  const columns = ['  "id" TEXT PRIMARY KEY']
  const indexes = []

  for (const [fieldName, field] of Object.entries(table.fields)) {
    const key = field.fieldName ?? fieldName
    const parts = [`  "${key}" ${column(field)}`]

    if (field.required) parts.push("NOT NULL")
    if (field.unique) parts.push("UNIQUE")
    if (field.references) {
      parts.push(
        `REFERENCES "${field.references.model}" ("${field.references.field}") ON DELETE CASCADE`
      )
      indexes.push(
        `CREATE INDEX IF NOT EXISTS "${name}_${key}_idx" ON "${name}" ("${key}");`
      )
    }
    columns.push(parts.join(" "))
  }

  lines.push(`CREATE TABLE IF NOT EXISTS "${name}" (`)
  lines.push(columns.join(",\n"))
  lines.push(");", "")

  // CREATE TABLE IF NOT EXISTS does nothing to a table that already exists, so
  // an upgrade that adds a column would leave a live database one column short
  // and fail at runtime with a raw "column does not exist". These catch it up.
  //
  // No NOT NULL or UNIQUE here on purpose: applying either to a table that
  // already has rows would fail, and the constraint is already present on any
  // database created from the CREATE above.
  const alters = Object.entries(table.fields).map(([fieldName, field]) => {
    const key = field.fieldName ?? fieldName
    return `ALTER TABLE "${name}" ADD COLUMN IF NOT EXISTS "${key}" ${column(field)};`
  })
  lines.push(...alters, "")

  if (indexes.length > 0) lines.push(...indexes, "")
}

const chatBlockPath = fileURLToPath(new URL("../netlify/lib/chat-schema.sql", import.meta.url))
lines.push(readFileSync(chatBlockPath, "utf8").trimEnd(), "")

const out = fileURLToPath(new URL("../netlify/lib/auth-schema.sql", import.meta.url))
writeFileSync(out, lines.join("\n"), "utf8")
console.log(`Wrote ${Object.keys(tables).length} auth tables plus the chat block to ${out}`)
